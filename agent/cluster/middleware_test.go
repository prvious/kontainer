package cluster

import (
	"net/http"
	"net/http/httptest"
	"testing"
)

func TestInternalAuth_ValidSecret(t *testing.T) {
	handler := InternalAuth("my-secret")(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.WriteHeader(http.StatusOK)
	}))

	req := httptest.NewRequest("GET", "/internal/health", nil)
	req.Header.Set(InternalSecretHeader, "my-secret")
	w := httptest.NewRecorder()
	handler.ServeHTTP(w, req)

	if w.Code != http.StatusOK {
		t.Errorf("expected 200, got %d", w.Code)
	}
}


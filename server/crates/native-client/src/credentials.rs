/// Owned secret bytes: redacted diagnostics, no clone, zeroed on drop.
struct SecretValue {
    value: Vec<u8>,
}

impl SecretValue {
    fn new(value: &str) -> Self {
        Self {
            value: value.as_bytes().to_vec(),
        }
    }

    fn expose(&self) -> &str {
        // Every constructor accepts `&str`, so the owned bytes are valid
        // UTF-8 by construction.
        std::str::from_utf8(&self.value).expect("secret bytes are valid UTF-8 by construction")
    }
}

impl std::fmt::Debug for SecretValue {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str("<redacted>")
    }
}

impl Drop for SecretValue {
    fn drop(&mut self) {
        self.value.fill(0);
    }
}

fn parse_prefixed(value: &str, prefix: &str) -> Result<SecretValue, CredentialError> {
    let rest = value.strip_prefix(prefix).ok_or(CredentialError)?;
    let (public_id, secret) = rest.split_once('.').ok_or(CredentialError)?;
    if !is_canonical_hex(public_id, PUBLIC_ID_HEX_LEN) || !is_canonical_hex(secret, SECRET_HEX_LEN)
    {
        return Err(CredentialError);
    }
    Ok(SecretValue::new(value))
}

/// Reject uppercase: the controller issues canonical lowercase hex only.
pub(crate) fn is_canonical_hex(value: &str, length: usize) -> bool {
    value.len() == length
        && value
            .bytes()
            .all(|byte| byte.is_ascii_digit() || matches!(byte, b'a'..=b'f'))
}

//! Redacted credential and PKCE types.
//!
//! Credentials cross the native boundary as typed per-call arguments, never as
//! client state. The wrappers validate canonical shapes, keep `Debug` and
//! `Display` redacted, refuse serialization and cloning, and zero their owned
//! bytes on drop. Plaintext is reachable only through the explicit
//! [`expose`](AccessCredential::expose) escape hatch.

use base64::{Engine, engine::general_purpose::URL_SAFE_NO_PAD};
use sha2::{Digest, Sha256};

const ACCESS_PREFIX: &str = "kta_";
const REFRESH_PREFIX: &str = "ktr_";
const PUBLIC_ID_HEX_LEN: usize = 32;
const SECRET_HEX_LEN: usize = 64;
/// RFC 7636 minimum verifier length.
const VERIFIER_MIN_LEN: usize = 43;
/// RFC 7636 maximum verifier length.
const VERIFIER_MAX_LEN: usize = 128;
/// 256 bits of entropy, which base64url-encodes to 43 characters.
const VERIFIER_BYTES: usize = 32;

/// The presented string does not match the canonical credential shape.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[error("credential is malformed")]
pub struct CredentialError;

/// A short-lived access credential issued by the controller.
///
/// Accepts only the canonical `kta_<32 lowercase hex>.<64 lowercase hex>`
/// shape. The value is redacted in diagnostics, cannot be serialized or
/// cloned, and is zeroed on drop.
///
/// ```
/// let credential = kontainer_native_client::AccessCredential::parse(
///     "kta_11111111111111111111111111111111.2222222222222222222222222222222222222222222222222222222222222222",
/// )
/// .unwrap();
/// assert_eq!(format!("{credential:?}"), "AccessCredential(<redacted>)");
/// assert!(credential.expose().starts_with("kta_"));
/// ```
///
/// A credential cannot be serialized into a body, log, or telemetry field:
///
/// ```compile_fail
/// let credential = kontainer_native_client::AccessCredential::parse(
///     "kta_11111111111111111111111111111111.2222222222222222222222222222222222222222222222222222222222222222",
/// )
/// .unwrap();
/// let control = serde_json::to_string("serde_json is available").unwrap();
/// assert!(!control.is_empty());
/// let _ = serde_json::to_string(&credential).unwrap();
/// ```
pub struct AccessCredential(SecretValue);

/// A rotating refresh credential issued by the controller.
///
/// Accepts only the canonical `ktr_<32 lowercase hex>.<64 lowercase hex>`
/// shape. It is redacted, non-serializable, non-cloneable, and zeroed on
/// drop. The controller revokes a whole session family when a consumed
/// refresh credential is presented again, so it must never be retried or
/// duplicated.
///
/// ```compile_fail
/// let credential = kontainer_native_client::RefreshCredential::parse(
///     "ktr_33333333333333333333333333333333.4444444444444444444444444444444444444444444444444444444444444444",
/// )
/// .unwrap();
/// let control = serde_json::to_string("serde_json is available").unwrap();
/// assert!(!control.is_empty());
/// let _ = serde_json::to_string(&credential).unwrap();
/// ```
pub struct RefreshCredential(SecretValue);

/// A PKCE S256 verifier generated by, or supplied to, the native caller.
///
/// The verifier never crosses the start endpoint; it is presented once at
/// redemption, in the JSON body. It is redacted, non-serializable,
/// non-cloneable, and zeroed on drop.
///
/// ```compile_fail
/// let verifier = kontainer_native_client::LoginVerifier::parse(
///     "dBjftJeZ4CVP-mB92K27uhbUJU1p1r_wW1gFWFOEjXk",
/// )
/// .unwrap();
/// let control = serde_json::to_string("serde_json is available").unwrap();
/// assert!(!control.is_empty());
/// let _ = serde_json::to_string(&verifier).unwrap();
/// ```
pub struct LoginVerifier(SecretValue);

impl AccessCredential {
    /// Parse and validate the canonical access-credential shape.
    pub fn parse(value: &str) -> Result<Self, CredentialError> {
        parse_prefixed(value, ACCESS_PREFIX).map(Self)
    }

    /// The plaintext credential for the transport that must present it.
    ///
    /// Callers use this only to construct an authorization header or hand the
    /// value to credential custody; it must never reach a URL, log line, or
    /// serialized structure.
    #[must_use]
    pub fn expose(&self) -> &str {
        self.0.expose()
    }
}

impl RefreshCredential {
    /// Parse and validate the canonical refresh-credential shape.
    pub fn parse(value: &str) -> Result<Self, CredentialError> {
        parse_prefixed(value, REFRESH_PREFIX).map(Self)
    }

    /// The plaintext credential for the caller that must persist it once.
    #[must_use]
    pub fn expose(&self) -> &str {
        self.0.expose()
    }
}

impl LoginVerifier {
    /// Generate a 256-bit RFC 7636 verifier from the ring CSPRNG.
    #[must_use]
    pub fn generate() -> Self {
        let mut bytes = [0u8; VERIFIER_BYTES];
        rustls::crypto::ring::default_provider()
            .secure_random
            .fill(&mut bytes)
            .expect("ring secure random must succeed");
        Self(SecretValue::new(&URL_SAFE_NO_PAD.encode(bytes)))
    }

    /// Parse a canonical RFC 7636 verifier: 43-128 unreserved characters.
    pub fn parse(value: &str) -> Result<Self, CredentialError> {
        if !(VERIFIER_MIN_LEN..=VERIFIER_MAX_LEN).contains(&value.len())
            || !value.bytes().all(|byte| {
                byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'.' | b'_' | b'~')
            })
        {
            return Err(CredentialError);
        }
        Ok(Self(SecretValue::new(value)))
    }

    /// Derive the RFC 7636 S256 challenge the controller persists for this
    /// verifier (`BASE64URL(SHA256(verifier))`).
    #[must_use]
    pub fn s256_challenge(&self) -> String {
        URL_SAFE_NO_PAD.encode(Sha256::digest(self.0.expose().as_bytes()))
    }

    /// The verifier plaintext for the redemption body only.
    pub(crate) fn expose(&self) -> &str {
        self.0.expose()
    }
}

